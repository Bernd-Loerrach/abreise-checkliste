#!/usr/bin/env python3
"""Regenerate vokabeln/conjugations.js from vokabeln/data.js.

Every card whose English starts with "to " and whose Portuguese is a single
infinitive (optionally with a leading/trailing "(...)" note or a reflexive
"-se") gets a present-tense table: [eu, tu, ele/ela, nós, eles/elas] and a
type (regular / irregular / impersonal).

Regular -ar/-er/-ir verbs are generated by rule (incl. -cer/-cir -> "ço").
Irregular and stem-changing verbs MUST be listed in OVR below, otherwise they
come out wrong (e.g. "refero" instead of "refiro"). Multi-word phrases are
skipped; add those to MANUAL if they need a table.

Usage:  python3 tools/gen_conjugations.py
"""
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "vokabeln"

OVR = {
    "ser": ["sou", "és", "é", "somos", "são"],
    "estar": ["estou", "estás", "está", "estamos", "estão"],
    "ter": ["tenho", "tens", "tem", "temos", "têm"],
    "ir": ["vou", "vais", "vai", "vamos", "vão"],
    "vir": ["venho", "vens", "vem", "vimos", "vêm"],
    "ver": ["vejo", "vês", "vê", "vemos", "veem"],
    "dizer": ["digo", "dizes", "diz", "dizemos", "dizem"],
    "fazer": ["faço", "fazes", "faz", "fazemos", "fazem"],
    "poder": ["posso", "podes", "pode", "podemos", "podem"],
    "querer": ["quero", "queres", "quer", "queremos", "querem"],
    "saber": ["sei", "sabes", "sabe", "sabemos", "sabem"],
    "trazer": ["trago", "trazes", "traz", "trazemos", "trazem"],
    "ouvir": ["ouço", "ouves", "ouve", "ouvimos", "ouvem"],
    "pedir": ["peço", "pedes", "pede", "pedimos", "pedem"],
    "despedir": ["despeço", "despedes", "despede", "despedimos", "despedem"],
    "seguir": ["sigo", "segues", "segue", "seguimos", "seguem"],
    "sentir": ["sinto", "sentes", "sente", "sentimos", "sentem"],
    "preferir": ["prefiro", "preferes", "prefere", "preferimos", "preferem"],
    "repetir": ["repito", "repetes", "repete", "repetimos", "repetem"],
    "referir": ["refiro", "referes", "refere", "referimos", "referem"],
    "dormir": ["durmo", "dormes", "dorme", "dormimos", "dormem"],
    "dar": ["dou", "dás", "dá", "damos", "dão"],
    "pôr": ["ponho", "pões", "põe", "pomos", "põem"],
    "doer": ["doo", "dóis", "dói", "doemos", "doem"],
    "sair": ["saio", "sais", "sai", "saímos", "saem"],
    "rir": ["rio", "ris", "ri", "rimos", "riem"],
    "incluir": ["incluo", "incluis", "inclui", "incluímos", "incluem"],
    "passear": ["passeio", "passeias", "passeia", "passeamos", "passeiam"],
    "chover": ["", "", "chove", "", "chovem"],
    "nevar": ["", "", "neva", "", "nevam"],
}
IMPERSONAL = {"chover", "nevar"}
MANUAL = {
    "ir buscar": {"f": ["vou buscar", "vais buscar", "vai buscar", "vamos buscar", "vão buscar"], "t": "irregular"},
}


def regular(inf):
    stem, end = inf[:-2], inf[-2:]
    ends = {"ar": ["o", "as", "a", "amos", "am"],
            "er": ["o", "es", "e", "emos", "em"],
            "ir": ["o", "es", "e", "imos", "em"]}[end]
    forms = [stem + e for e in ends]
    if end in ("er", "ir") and stem.endswith("c"):
        forms[0] = stem[:-1] + "ço"
    return forms


def reflexive(forms):
    clitics = ["-me", "-te", "-se", "-nos", "-se"]
    out = []
    for i, (f, c) in enumerate(zip(forms, clitics)):
        if not f:
            out.append("")
            continue
        if i == 3 and f.endswith("s"):
            f = f[:-1]  # nós: chamamos -> chamamo-nos
        out.append(f + c)
    return out


def core_of(pt):
    s = re.sub(r"^\([^)]*\)\s*", "", pt)
    s = re.sub(r"\s*\([^)]*\)$", "", s)
    refl = bool(re.search(r"-se$", s))
    return re.sub(r"-se$", "", s).strip(), refl


def main():
    src = (ROOT / "data.js").read_text()
    pairs = re.findall(r'\{ pt: "([^"]+)", en: "([^"]+)"', src)
    conj = {}
    for pt, en in pairs:
        if not en.startswith("to "):
            continue
        core, refl = core_of(pt)
        if " " in core or not re.search(r"(ar|er|ir|or|ôr)$", core):
            continue
        forms = OVR[core][:] if core in OVR else regular(core)
        if refl:
            forms = reflexive(forms)
        kind = "impersonal" if core in IMPERSONAL else ("irregular" if core in OVR else "regular")
        conj[pt] = {"f": forms, "t": kind}
    conj.update(MANUAL)

    lines = [
        "// Present-tense (presente do indicativo) conjugations for the course verbs.",
        "// CONJ[pt] = { f: [eu, tu, ele/ela, nós, eles/elas], t: regular|irregular|impersonal }.",
        "// GENERATED by tools/gen_conjugations.py — edit that script, not this file.",
        "",
        "const CONJ = {",
    ]
    for pt in sorted(conj):
        e = conj[pt]
        lines.append(f'  {json.dumps(pt, ensure_ascii=False)}: {{ f: {json.dumps(e["f"], ensure_ascii=False)}, t: {json.dumps(e["t"])} }},')
    lines += ["};", ""]
    (ROOT / "conjugations.js").write_text("\n".join(lines))
    print(f"{len(conj)} verbs:", dict(Counter(v["t"] for v in conj.values())))


if __name__ == "__main__":
    main()
