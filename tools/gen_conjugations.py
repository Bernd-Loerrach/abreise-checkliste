def regular(inf):
    stem, end = inf[:-2], inf[-2:]
    ends = {"ar": ["o", "as", "a", "amos", "am"],
            "er": ["o", "es", "e", "emos", "em"],
            "ir": ["o", "es", "e", "imos", "em"]}[end]
    forms = [stem + e for e in ends]
    if end in ("er", "ir") and stem.endswith("c"):
        forms[0] = stem[:-1] + "ço"
    return forms


def past_regular(inf):
    stem, end = inf[:-2], inf[-2:]
    ends = {"ar": ["ei", "aste", "ou", "ámos", "aram"],
            "er": ["i", "este", "eu", "emos", "eram"],
            "ir": ["i", "iste", "iu", "imos", "iram"]}[end]
    forms = [stem + e for e in ends]
    if end == "ar":  # keep the sound before -ei: ficar->fiquei, chegar->cheguei, almoçar->almocei
        if stem.endswith("c"):
            forms[0] = stem[:-1] + "quei"
        elif stem.endswith("g"):
            forms[0] = stem[:-1] + "guei"
        elif stem.endswith("ç"):
            forms[0] = stem[:-1] + "cei"
    return forms


def reflexive(forms):
    clitics = ["-me", "-te", "-se", "-nos", "-se"]
    out = []
    for i, (f, c) in enumerate(zip(forms, clitics)):
        if not f:
            out.append("")
            continue
        if i == 3 and f.endswith("s"):
            f = f[:-1]  # nós: chamamos -> chamamo-nos
        out.append(f + c)
    return out


def core_of(pt):
    s = re.sub(r"^\([^)]*\)\s*", "", pt)
    s = re.sub(r"\s*\([^)]*\)$", "", s)
    refl = bool(re.search(r"-se$", s))
    return re.sub(r"-se$", "", s).strip(), refl


def main():
    src = (ROOT / "data.js").read_text()
    pairs = re.findall(r'\{ pt: "([^"]+)", en: "([^"]+)"', src)
    conj = {}
    for pt, en in pairs:
        if not en.startswith("to "):
            continue
        core, refl = core_of(pt)
        if " " in core or not re.search(r"(ar|er|ir|or|ôr)$", core):
            continue
        forms = OVR[core][:] if core in OVR else regular(core)
        past = PPS_OVR[core][:] if core in PPS_OVR else past_regular(core)
        if refl:
            forms, past = reflexive(forms), reflexive(past)
        kind = "impersonal" if core in IMPERSONAL else ("irregular" if core in OVR else "regular")
        pkind = "impersonal" if core in IMPERSONAL else ("irregular" if core in PPS_OVR else "regular")
        conj[pt] = {"f": forms, "t": kind, "p": past, "tp": pkind}
    conj.update(MANUAL)

    lines = [
        "// Present-tense (presente do indicativo) conjugations for the course verbs.",
        "// CONJ[pt] = { f: present, t: type, p: pretérito perfeito, tp: type } — forms are [eu, tu, ele/ela/você, nós, eles/elas/vocês].",
        "// GENERATED by tools/gen_conjugations.py — edit that script, not this file.",
        "",
        "const CONJ = {",
    ]
    for pt in sorted(conj):
        e = conj[pt]
        lines.append(f'  {json.dumps(pt, ensure_ascii=False)}: {{ f: {json.dumps(e["f"], ensure_ascii=False)}, t: {json.dumps(e["t"])}, p: {json.dumps(e["p"], ensure_ascii=False)}, tp: {json.dumps(e["tp"])} }},')
    lines += ["};", ""]
    (ROOT / "conjugations.js").write_text("\n".join(lines))
    print(f"{len(conj)} verbs | present:", dict(Counter(v["t"] for v in conj.values())), "| past:", dict(Counter(v["tp"] for v in conj.values())))


if __name__ == "__main__":
    main()
